class FoodItem {
  final String id;
  final String name;
  final String category; // 'Makanan Berat', 'Buah', 'Sayuran', 'Camilan'
  final String image;
  final int calories;
  final double protein;
  final double fat;
  final double carbs;
  final double sugar;
  final String vitamins;
  final String portion;
  final String description;

  const FoodItem({
    required this.id,
    required this.name,
    required this.category,
    required this.image,
    required this.calories,
    required this.protein,
    required this.fat,
    required this.carbs,
    required this.sugar,
    required this.vitamins,
    required this.portion,
    required this.description,
  });
}

